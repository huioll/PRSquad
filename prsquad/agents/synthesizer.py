"""Synthesizer node — fan-in step that consolidates all agent reports into a single PR comment."""
from __future__ import annotations

from typing import Any

from .state import GraphState

_HEADER = "🤖 **PRSquad Review** — multi-agent automated review\n\n"


def synthesize(state: GraphState) -> dict[str, Any]:
    """Render the per-agent reports as one Markdown blob suitable for a PR comment."""
    parts = [_HEADER]
    for report in state.get("reports", []):
        parts.append(_render_section(report.agent, report.summary, report.payload, report.error))
    parts.append("\n---\n*Generated by PRSquad — see https://github.com/USER/prsquad*")
    return {"markdown": "".join(parts)}


def _render_section(agent: str, summary: str, payload: dict, error: str | None) -> str:
    icons = {"reviewer": "🧐", "security": "🛡️", "tests": "🧪", "docs": "📚"}
    icon = icons.get(agent, "•")
    out = [f"\n### {icon} {agent.title()}\n", f"{summary}\n"]
    if error:
        out.append(f"\n> ⚠️ agent error: `{error}`\n")
        return "".join(out)

    # Render the bits we know how to format prettily.
    if comments := payload.get("comments"):
        out.append("\n**Comments**\n")
        for c in comments:
            out.append(f"- _{c.get('severity','?')}_  `{c.get('file','?')}` — {c.get('message','')}\n")
    if findings := payload.get("findings"):
        out.append("\n**Findings**\n")
        for f in findings:
            out.append(f"- _{f.get('severity','?')}_  **{f.get('rule','?')}** — {f.get('message','')}\n")
    if suggestions := payload.get("suggestions"):
        out.append("\n**Suggested tests**\n")
        for s in suggestions:
            out.append(f"- {s.get('target','?')}: {s.get('case','')}\n")
    if drafts := payload.get("drafts"):
        out.append("\n**Draft docstrings**\n")
        for d in drafts:
            out.append(f"- `{d.get('symbol','?')}`: {d.get('doc','')}\n")
    return "".join(out)
